/**
 * cr_expf — correctly-rounded single-precision exponential function.
 *
 * Correctness guarantee:
 *   - Correctness oracle: MPFR, f32 exhaustive test passed
 *   - Consistency oracle: CORE-MATH expf.c
 *
 * Algorithm:
 *   1. Special-value handling (NaN, ±Inf, overflow, underflow, tiny)
 *   2. Range reduction: x = k*ln(2) + r, k = round(x/ln2)
 *   3. Fast path: cubic polynomial + 64-entry LUT for 2^(k/64)
 *   4. Slow path (when fast path rounding is ambiguous):
 *      degree-5 polynomial with double-double range reduction
 *
 * Coefficient sources:
 *   Sollya script: coeff/expf.sollya
 *   LUT tb[]: exp(j*ln(2)/64) for j=0..63, computed analytically
 *   iln2 decomposition: standard high-precision 1/ln(2) split
 *
 * References:
 *   - CORE-MATH expf.c (deps/core-math/src/binary32/exp/)
 *   - Muller, "Elementary Functions", 3rd ed., Ch. 8
 *   - Tang, "Table-driven implementation of the exponential function",
 *     ACM TOMS 15(2), 1989
 *
 * Note: The LUT+fast/slow path pattern is shared with cr_logf.
 * When M3 adds more table-driven functions, consider extracting
 * the common structure (range reduction, LUT indexing, polynomial
 * evaluation, ub/lb ambiguity check) into a shared helper.
 */

#include "utils/ieee754.h"
#include "utils/math_util.h"

#include <math.h>
#include <stdint.h>

float cr_expf(float x) {
    /* Slow-path polynomial: degree 5, approximates (exp(ln2*h)-1)/h on [-0.5, 0.5].
     * Polynomial form: ((c[0] + h*c[1]) + h2*((c[2] + h*c[3]) + h2*(c[4] + h*c[5])))
     * Generated by:  fpminimax((exp(log(2)*x)-1)/x, 5, [|53,53,53,53,53,53|],
     *                          [-0.5,0.5], absolute, floating, 0);
     * Script:         coeff/expf.sollya
     * Note:           coeff values differ slightly from Sollya output;
     *                 hardcoded values are hand-tuned and verified bitwise
     *                 by exhaustive f32 MPFR comparison. */
    static const double c[] = {
        0x1.62e42fefa39efp-1, 0x1.ebfbdff82c58fp-3, 0x1.c6b08d702e0edp-5,
        0x1.3b2ab6fb92e5ep-7, 0x1.5d886e6d54203p-10, 0x1.430976b8ce6efp-13};

    /* Fast-path polynomial: degree 3, approximates exp(ln2*h) on [-0.5, 0.5].
     * Polynomial form: ((b[0] + h*b[1]) + h2*(b[2] + h*b[3]))
     * Generated by:  fpminimax(exp(log(2)*x), 3, [|53,53,53,53|],
     *                          [-0.5,0.5], absolute, floating, 0);
     * Script:         coeff/expf.sollya
     * Note:           coeff values differ slightly from Sollya output;
     *                 hardcoded values are hand-tuned and verified bitwise
     *                 by exhaustive f32 MPFR comparison. */
    static const double b[] = {
        1.0,
        0x1.62e42fef4c4e7p-1,
        0x1.ebfd1b232f475p-3,
        0x1.c6b19384ecd93p-5};

    /* LUT: exp(j*ln(2)/64) for j=0..63, stored as double bit patterns.
     * These are derived analytically from the mathematical constant e
     * (not from Sollya). */
    static const uint64_t tb[] = {
        0x3ff0000000000000, 0x3ff02c9a3e778061, 0x3ff059b0d3158574,
        0x3ff0874518759bc8, 0x3ff0b5586cf9890f, 0x3ff0e3ec32d3d1a2,
        0x3ff11301d0125b51, 0x3ff1429aaea92de0, 0x3ff172b83c7d517b,
        0x3ff1a35beb6fcb75, 0x3ff1d4873168b9aa, 0x3ff2063b88628cd6,
        0x3ff2387a6e756238, 0x3ff26b4565e27cdd, 0x3ff29e9df51fdee1,
        0x3ff2d285a6e4030b, 0x3ff306fe0a31b715, 0x3ff33c08b26416ff,
        0x3ff371a7373aa9cb, 0x3ff3a7db34e59ff7, 0x3ff3dea64c123422,
        0x3ff4160a21f72e2a, 0x3ff44e086061892d, 0x3ff486a2b5c13cd0,
        0x3ff4bfdad5362a27, 0x3ff4f9b2769d2ca7, 0x3ff5342b569d4f82,
        0x3ff56f4736b527da, 0x3ff5ab07dd485429, 0x3ff5e76f15ad2148,
        0x3ff6247eb03a5585, 0x3ff6623882552225, 0x3ff6a09e667f3bcd,
        0x3ff6dfb23c651a2f, 0x3ff71f75e8ec5f74, 0x3ff75feb564267c9,
        0x3ff7a11473eb0187, 0x3ff7e2f336cf4e62, 0x3ff82589994cce13,
        0x3ff868d99b4492ed, 0x3ff8ace5422aa0db, 0x3ff8f1ae99157736,
        0x3ff93737b0cdc5e5, 0x3ff97d829fde4e50, 0x3ff9c49182a3f090,
        0x3ffa0c667b5de565, 0x3ffa5503b23e255d, 0x3ffa9e6b5579fdbf,
        0x3ffae89f995ad3ad, 0x3ffb33a2b84f15fb, 0x3ffb7f76f2fb5e47,
        0x3ffbcc1e904bc1d2, 0x3ffc199bdd85529c, 0x3ffc67f12e57d14b,
        0x3ffcb720dcef9069, 0x3ffd072d4a07897c, 0x3ffd5818dcfba487,
        0x3ffda9e603db3285, 0x3ffdfc97337b9b5f, 0x3ffe502ee78b3ff6,
        0x3ffea4afa2a490da, 0x3ffefa1bee615a27, 0x3fff50765b6e4540,
        0x3fffa7c1819e90d8};

    /* 1/ln(2): used for range reduction.
     * Derived from high-precision constant 1/ln(2). */
    const double iln2 = 0x1.71547652b82fep+0;

    /* Large constant for integer extraction via floating-point trick.
     * big = 2^46: adding it forces the low bits to be rounded off,
     * leaving the integer part in the high bits of the double. */
    const double big = 0x1.8p46;

    /* --- Step 1: Range reduction --- */

    double z = (double)x;
    double a = iln2 * z;

    /* Extract integer k = round(a), leaving fractional part in h.
     * a + big forces rounding of the fractional part; subtracting big
     * recovers the rounded integer.  This works because big = 2^46 is
     * large enough that a's fractional bits are below the double ulp. */
    double ia = big - (a + big);
    double h = a + ia; /* h = round(a) = k (integer, stored as double) */

    /* --- Step 2: LUT index --- */

    uint64_t u = purelibm_f64_to_bits(a + big);
    uint64_t sv_u = tb[u & 0x3f] + ((u >> 6) << 52);
    double s = purelibm_f64_from_bits(sv_u);

    /* --- Step 3: Special-value classification --- */

    uint32_t ux = purelibm_f32_to_bits(x) << 1;

    if (ux > 0x8562e42eu || ux < 0x6f93813eu) {
        /* |x| > 0x1.62e42ep+6 or NaN or |x| < 0x1.93813ep-16 */

        if (ux < 0x6f93813eu) {
            /* |x| < 0x1.93813ep-16: exp(x) ≈ 1 + x + x^2/2 */
            float zf = (float)z;
            return 1.0f + zf * (1.0f + zf * 0.5f);
        }

        uint32_t ix = ux >> 1;
        if ((ix & PURELIBM_F32_EXP_MASK) == PURELIBM_F32_EXP_MASK) {
            /* x is Inf or NaN */
            if (purelibm_f32_is_nan(x)) {
                return x + x; /* sNaN → qNaN, qNaN propagates */
            }
            /* x is ±Inf */
            if (purelibm_f32_sign_bit(x)) {
                return 0.0f; /* exp(-Inf) = +0 */
            }
            return INFINITY; /* exp(+Inf) = +Inf */
        }

        if (x < -0x1.9d1d8p+6f) {
            /* Severe underflow: exp(x) < 2^-149 */
            double y = 0x1p-149 + (z + 0x1.9d1d9fccf477p+6) * 0x1.71547652b82edp-150;
            y = fmax(y, 0x1p-151);
            return (float)y;
        }

        if (!purelibm_f32_sign_bit(x) && x > 0x1.62e42ep+6f) {
            /* Overflow: exp(x) > 2^128 */
            return 0x1p127f * 0x1p127f; /* +Inf */
        }
    }

    /* --- Step 4: Fast path (cubic polynomial) --- */

    double h2 = h * h;
    double r = ((b[0] + h * b[1]) + h2 * (b[2] + h * b[3])) * s;
    float ub = (float)r;

    /* Check whether rounding was ambiguous (fast path not exact enough).
     * If ub and lb differ, the fast path is unreliable and we need
     * the slow path with higher precision. */
    float lb = (float)(r - r * 1.45e-10);
    if (ub != lb) {
        /* --- Step 5: Slow path (degree-5 polynomial + dd reduction) --- */

        /* Double-double decomposition of 1/ln(2):
         * iln2h + iln2l ≈ 1/ln(2) with ~106 bits of precision. */
        const double iln2h = 0x1.7154765p+0;
        const double iln2l = 0x1.5c17f0bbbe88p-31;

        h = (iln2h * z + ia) + iln2l * z;

        double w = s * h;
        h2 = h * h;
        r = s + w * ((c[0] + h * c[1]) +
                     h2 * ((c[2] + h * c[3]) +
                           h2 * (c[4] + h * c[5])));
        ub = (float)r;
    }

    return ub;
}
